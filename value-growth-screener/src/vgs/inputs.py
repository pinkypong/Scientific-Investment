"""Load analysis inputs, keeping reported facts and human assumptions in separate files.

  facts/<TICKER>.json        security, as_of, objective, sources (and optional analyst block).
                             Generated by collection; safe to regenerate at any time.
  assumptions/<TICKER>.json  {"ticker": "<TICKER>", "assumptions": {...}}.
                             Written by a person only; collection never touches it.

A facts file that carries an ``assumptions`` block is refused, so a regenerated facts file
can never silently replace what a person wrote. A security without an assumptions file is
still screened (Step 1); its Step 2 is simply empty.
"""

from __future__ import annotations

import json
import re
from copy import deepcopy
from pathlib import Path
from typing import Any

_SAFE_NAME = re.compile(r"[^A-Za-z0-9._-]")


def assumptions_path(directory: str | Path, ticker: str) -> Path:
    return Path(directory) / f"{_SAFE_NAME.sub('_', ticker)}.json"


def merge_assumptions(facts: dict[str, Any], document: dict[str, Any] | None) -> dict[str, Any]:
    """Return a new payload: the facts plus the person's assumptions (or none)."""
    if facts.get("assumptions"):
        raise ValueError("a facts file must not carry assumptions; keep them in assumptions/<TICKER>.json")
    ticker = str(facts.get("security", {}).get("ticker") or "").strip()
    if not ticker:
        raise ValueError("facts file needs security.ticker")
    payload = deepcopy(facts)
    payload["assumptions"] = {}
    if document is None:
        return payload
    if str(document.get("ticker") or "").strip() != ticker:
        raise ValueError(f"assumptions file is for {document.get('ticker')!r}, not {ticker!r}")
    if not isinstance(document.get("assumptions"), dict):
        raise ValueError(f"{ticker}: assumptions file needs an 'assumptions' object")
    payload["assumptions"] = deepcopy(document["assumptions"])
    return payload


def load_payload(path: str | Path, assumptions_dir: str | Path | None = None) -> dict[str, Any]:
    """Read one input. Without ``assumptions_dir`` the file is used as-is (combined format)."""
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if assumptions_dir is None:
        return data
    ticker = str(data.get("security", {}).get("ticker") or "").strip()
    target = assumptions_path(assumptions_dir, ticker) if ticker else None
    document = json.loads(target.read_text(encoding="utf-8")) if target and target.exists() else None
    return merge_assumptions(data, document)


def split_payload(payload: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any]]:
    """Split a combined payload into (facts, assumptions document). Used for migration."""
    facts = deepcopy(payload)
    assumptions = facts.pop("assumptions", {}) or {}
    ticker = str(facts.get("security", {}).get("ticker") or "").strip()
    if not ticker:
        raise ValueError("payload needs security.ticker")
    return facts, {"ticker": ticker, "assumptions": assumptions}
